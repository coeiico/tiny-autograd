"""
Write build/values.tex: the numbers the figures quote, as macros, read from data/.

Accuracies and error counts from the boundary files, final validation accuracies from the
curves, and every value and gradient of the one-neuron graph. Nothing is computed here
except formatting (and counting the misclassified points the files mark).
"""

import csv
import json

import numpy as np

lines = ['% Generated by src/values.py from data/; do not edit.']

for run, tag in (('default-seed0', 'mlp'), ('linear-seed0', 'lin')):
  d = np.load(f'data/boundary-{run}.npz')
  wrong = int(((d['test_logits'] > 0) != (d['test_y'] == 1)).sum())
  lines.append(f'\\def\\acc{tag}{{{100 * float(d["test_accuracy"]):.1f}}}\\def\\wrong{tag}{{{wrong}}}\\def\\ntest{{{len(d["test_y"])}}}')

for run, tag in (('default-seed0', 'A'), ('default-seed1', 'B'), ('default-seed2', 'C'), ('linear-seed0', 'Lin')):
  with open(f'data/curves-{run}.csv') as f:
    last = list(csv.DictReader(f))[-1]
  lines.append(f'\\def\\final{tag}{{{100 * float(last["val_accuracy"]):.1f}}}')

# The one-neuron graph: name each node by its role, then write its value and gradient.
nodes = json.load(open('data/graph-neuron.json'))['nodes']
by_id = {n['id']: n for n in nodes}
leaf_names = {'x₁': 'xone', 'x₂': 'xtwo', 'w₁': 'wone', 'w₂': 'wtwo', 'b': 'bias', 'output': 'out'}
for n in nodes:
  inputs = {by_id[i]['label'] for i in n['inputs']}
  if n['label'] in leaf_names:
    name = leaf_names[n['label']]
  elif n['op'] == '×':
    name = 'pone' if 'x₁' in inputs else 'ptwo'
  elif n['op'] == '+':
    name = 'z' if 'b' in inputs else 's'
  else:
    continue
  lines.append(f'\\def\\v{name}{{{n["data"]:.2f}}}\\def\\g{name}{{{n["grad"]:.2f}}}')

with open('build/values.tex', 'w') as f:
  f.write('\n'.join(lines) + '\n')

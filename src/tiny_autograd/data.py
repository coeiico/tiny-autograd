"""
The two moons toy dataset, generated by hand.

Two interleaved half circles, one per class, plus Gaussian noise. No straight line
separates them, so a linear model must fail and a network has to bend its boundary.
"""

import hashlib
from dataclasses import asdict, dataclass
from typing import Any

import numpy as np

GENERATOR_VERSION = 1
"""Bump when make_moons changes, so old runs' data stays identifiable."""


@dataclass(frozen=True)
class MoonsArgs:
  n_train: int = 100
  """Few points on purpose: the scalar engine builds a graph node per multiply."""
  n_val: int = 200
  n_test: int = 1000
  noise: float = 0.15
  """Standard deviation of the Gaussian noise added to each coordinate."""


@dataclass(frozen=True)
class Split:
  x: np.ndarray
  """Points, float64 [n, 2]."""
  y: np.ndarray
  """Labels, int64 [n], 0 for the upper moon and 1 for the lower one."""


def make_moons(n: int, noise: float, rng: np.random.Generator) -> Split:
  """
  Draw n points, each from a random moon at a random angle.

  The angle is sampled rather than spaced evenly (as scikit-learn does), so every point is
  an independent draw and any split of them is a fair held-out set.
  """
  y = rng.integers(0, 2, size=n)
  t = rng.uniform(0, np.pi, size=n)
  # Upper moon: the top half of the unit circle. Lower moon: the same arc flipped and shifted
  # right by 1 and down by 0.5, so its tips poke into the upper moon's hollow.
  upper = np.stack([np.cos(t), np.sin(t)], axis=1)
  lower = np.stack([1 - np.cos(t), 0.5 - np.sin(t)], axis=1)
  x = np.where(y[:, None] == 0, upper, lower) + rng.normal(0, noise, size=(n, 2))
  return Split(x=x, y=y)


def make_splits(args: MoonsArgs, seed: int) -> dict[str, Split]:
  """
  Train, validation and test sets from one seeded stream, split by point.

  Every point is an independent draw from the same distribution, so the point is the right
  split unit: there are no related examples that could leak across splits.
  """
  rng = np.random.default_rng(seed)
  sizes = {'train': args.n_train, 'val': args.n_val, 'test': args.n_test}
  return {name: make_moons(n, args.noise, rng) for name, n in sizes.items()}


def describe(args: MoonsArgs, seed: int, splits: dict[str, Split]) -> dict[str, Any]:
  """Everything needed to identify the data a run saw: settings, seed, balance and a hash."""
  digest = hashlib.sha256()
  for name in sorted(splits):
    digest.update(splits[name].x.tobytes())
    digest.update(splits[name].y.tobytes())
  return {
    'generator': 'two moons',
    'generator_version': GENERATOR_VERSION,
    'settings': asdict(args),
    'seed': seed,
    'split_unit': 'point (independent draws)',
    'class_1_fraction': {name: float(s.y.mean()) for name, s in splits.items()},
    'sha256': digest.hexdigest(),
  }
